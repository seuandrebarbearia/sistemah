import test from 'node:test';
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import worker, { Catalog } from './worker.js';

test('Cloudflare adapter enforces server login and persists catalog and session across instances', async t => {
  const db = new DatabaseSync(':memory:'); t.after(() => db.close());
  const ctx = { storage: { sql: { exec(query,...args) { const rows = db.prepare(query).all(...args); return { toArray: () => rows }; } } } };
  const secret = { ADMIN_PASSWORD:'Only-for-test-39-never-deployed' };
  let object = new Catalog(ctx, secret);
  let assetsCalled = 0;
  const env = { CATALOG:{idFromName:x=>x,get:()=>object}, ASSETS:{fetch:async req=>{ assetsCalled++; return new Response('static asset', {status:new URL(req.url).pathname.endsWith('.html')?200:404}); }} };
  const request = (path,method='GET',data,cookie,origin='https://sistemah.example') => worker.fetch(new Request('https://sistemah.example'+path,{method,headers:{Origin:origin,'Content-Type':'application/json', 'CF-Connecting-IP':'192.0.2.1',...(cookie?{Cookie:cookie}:{})},...(data===undefined?{}:{body:JSON.stringify(data)})}), env);
  assert.equal((await request('/admin.html')).status,303);
  assert.equal(assetsCalled,0);
  assert.equal((await request('/')).status,200);
  assert.equal((await request('/api/session','GET',undefined,'logado=true')).status,401);
  const item={nome:'Produto teste',descricao:'Teste',preco:10,categoria:'lanche'};
  assert.equal((await request('/api/products','POST',item,'logado=true')).status,401);
  assert.equal((await request('/api/login','POST',{senha:secret.ADMIN_PASSWORD},undefined,'https://evil.example')).status,403);
  const login=await request('/api/login','POST',{senha:secret.ADMIN_PASSWORD});
  assert.equal(login.status,200);
  const header=login.headers.get('Set-Cookie');
  for(const flag of ['HttpOnly','Secure','SameSite=Strict','__Host-sistemah=']) assert.ok(header.includes(flag));
  const cookie=header.split(';')[0];
  assert.equal((await request('/admin.html','GET',undefined,cookie)).status,200);
  assert.equal((await request('/api/products','POST',{...item,imagem:'data:image/svg+xml;base64,AAAA'},cookie)).status,400);
  const created=await request('/api/products','POST',item,cookie); assert.equal(created.status,201);
  const product=await created.json();
  object=new Catalog(ctx,secret);
  assert.equal((await request('/api/session','GET',undefined,cookie)).status,200);
  assert.equal((await (await request('/api/products')).json())[0].id,product.id);
  assert.equal((await request('/api/products/'+product.id,'DELETE',undefined,undefined)).status,401);
  assert.equal((await request('/api/products/'+product.id,'DELETE',undefined,cookie,'https://evil.example')).status,403);
  assert.equal((await request('/api/logout','POST',undefined,cookie)).status,200);
  assert.equal((await request('/api/session','GET',undefined,cookie)).status,401);
  const second=await request('/api/login','POST',{senha:secret.ADMIN_PASSWORD});
  const secondCookie=second.headers.get('Set-Cookie').split(';')[0];
  object=new Catalog(ctx,{ADMIN_PASSWORD:'changed-secret-for-test-only'});
  assert.equal((await request('/api/session','GET',undefined,secondCookie)).status,401);
  object=new Catalog(ctx,secret);
  db.prepare('UPDATE sessions SET expiry=0').run();
  assert.equal((await request('/api/session','GET',undefined,secondCookie)).status,401);
  for(let n=0;n<5;n++) assert.equal((await request('/api/login','POST',{senha:'wrong'})).status,401);
  object=new Catalog(ctx,secret);
  assert.equal((await request('/api/login','POST',{senha:secret.ADMIN_PASSWORD})).status,429);
  for(const path of ['/worker.js','/server.js','/.env','/data/products.json','/wrangler.jsonc']) assert.equal((await request(path)).status,404);
  object=new Catalog(ctx,{});
  assert.equal((await request('/api/login','POST',{senha:secret.ADMIN_PASSWORD})).status,503);
});
